def write_power(power_pct: float) -> None:
    data = list(struct.pack('<f', float(power_pct)))
    msg  = smbus2.i2c_msg.write(SLAVE_ADDR, data)
    i2c.i2c_rdwr(msg)

def read_confirmation() -> float:
    msg = smbus2.i2c_msg.read(SLAVE_ADDR, 4)
    i2c.i2c_rdwr(msg)
    (valor,) = struct.unpack('<f', bytes(msg))
    return valor

def calcular_potencia_real(power_int: int) -> tuple:
    area   = area_lut.get(power_int, 0.0)
    tiempo = tiempo_lut.get(power_int, 0.0)
    # P = V² × ∫sin²(ωt)dt = V² × Área
    p_real = (VOLTAJE ** 2) * area
    return round(p_real, 1), round(tiempo, 4)

def main():
    print("=" * 45)
    print("  Control de foco incandescente via I2C")
    print(f"  Red: {VOLTAJE}V | Resolucion: 1%")
    print("=" * 45)
    print("  0 = apagado | 100 = maxima potencia")
    print("  Ctrl+C para salir\n")

    while True:
        try:
            raw   = input("Potencia [0-100]%: ").strip()
            power = float(raw)

            if not (0.0 <= power <= 100.0):
                print("  Error: valor fuera de rango.\n")
                continue

            write_power(power)
            time.sleep(0.05)
            confirmado = read_confirmation()

            if confirmado < 0:
                print("  Error reportado por RP2040.\n")
            else:
                power_int       = int(confirmado)
                p_real, t_ms    = calcular_potencia_real(power_int)
                p_max           = (VOLTAJE ** 2) * area_lut[0]
                p_pct_real      = round((p_real / p_max) * 100, 1)
                print(f"  Porcentaje solicitado : {power:.1f}%")
                print(f"  Porcentaje aplicado   : {power_int}%")
                print(f"  Tiempo de encendido   : {t_ms:.4f} ms")
                print(f"  Potencia real         : {p_real:.1f} W")
                print(f"  Potencia maxima       : {p_max:.1f} W")
                print(f"  Potencia relativa     : {p_pct_real:.1f}%\n")

        except ValueError:
            print("  Entrada invalida.\n")
        except KeyboardInterrupt:
            print("\n  Apagando...")
            write_power(0)
            break
        except Exception as e:
            print(f"  Error I2C: {e}\n")
            time.sleep(0.5)

if __name__ == '__main__':
    main()